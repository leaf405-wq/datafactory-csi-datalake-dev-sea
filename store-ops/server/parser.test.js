import assert from "node:assert/strict";
import test from "node:test";
import { SAMPLE_CONTRACT, parseContract } from "./parser.js";

test("示例合同能抽出两者取高和免租期", () => {
  const parsed = parseContract(SAMPLE_CONTRACT);
  assert.equal(parsed.model, "HIGHER_OF_TWO");
  assert.equal(parsed.values.fixed_rent, 90000);
  assert.equal(parsed.values.rate, 0.11);
  assert.equal(parsed.values.reference_sales, 980000);
  assert.equal(parsed.values.rent_free_start, "2026-03-01");
  assert.ok(parsed.confidence >= 0.8);
  const shown = Object.fromEntries(parsed.fields.map((field) => [field.label, field.field_value]));
  assert.equal(shown["合同编号"], "SH-IXT-2026-014");
  assert.equal(shown["品牌"], "主品牌");
  assert.equal(shown["店铺名称"], "上海前滩太古里店");
  assert.equal(shown["商场"], "前滩太古里");
  assert.equal(shown["区域"], "华东");
  assert.equal(shown["城市"], "上海");
  assert.equal(shown["业主"], "太古地产");
  assert.equal(shown["租赁期限"], "2026-03-01 至 2029-02-28");
  assert.equal(shown["免租期"], "2026-03-01 至 2026-03-15");
  assert.equal(shown["免租是否免物业"], "否");
  assert.equal(shown["租金模式"], "两者取高");
  assert.equal(shown["固定租金"], "90000");
  assert.equal(shown["扣点比例"], "11%");
  assert.equal(shown["保底销售额"], "1200000");
  assert.equal(shown["物业费"], "12000");
  assert.equal(shown["推广费"], "4000");
  assert.equal(shown["水电费"], "2500");
  assert.equal(shown["增值税率"], "9%");
  assert.equal(shown["计租面积"], "98");
  assert.equal(shown["销售面积"], "86");
  assert.equal(shown["参考月销售"], "980000");
});
